"""
Complaint Drafting Agent.

Converts a citizen's described situation into a structured formal complaint
(consumer, police, cybercrime, labour, RTI, grievance, etc.) and exports it
as a downloadable Word document.
"""
from src.common.json_llm import call_llm_json
from src.rag.prompts import SYSTEM_PROMPT

COMPLAINT_PROMPT = """A citizen described this situation:

\"\"\"{situation}\"\"\"

Draft a formal complaint based on it. Respond with ONLY a JSON object (no
markdown, no commentary, no code fences) with exactly these keys:

{{
  "complaint_type": "e.g. Consumer Complaint / Police Complaint / Cybercrime Complaint / Labour Complaint / RTI Application / Grievance Letter",
  "issue_summary": "one line summary of the issue, in {language}",
  "complainant_placeholder": "[Your Name, Address, Phone, Email]",
  "respondent_placeholder": "[Name/Company/Authority being complained against]",
  "description": "a clear, formal 3-5 sentence description of what happened, written in {language}",
  "relief_requested": "what the citizen is asking for (refund, action taken, investigation, etc.), in {language}",
  "attachments": ["list", "of", "documents", "the", "citizen", "should", "attach"],
  "signature_placeholder": "[Signature]\\n[Date]"
}}
"""


def generate_complaint(situation: str, language: str = "English") -> dict:
    prompt = COMPLAINT_PROMPT.format(situation=situation, language=language)
    result = call_llm_json(SYSTEM_PROMPT, prompt)
    result["_situation"] = situation
    return result


def export_complaint_docx(complaint: dict, output_path: str) -> str:
    """Renders the structured complaint dict into a formatted .docx file."""
    from docx import Document

    doc = Document()
    doc.add_heading(complaint.get("complaint_type", "Complaint"), level=1)

    doc.add_paragraph(f"Complainant: {complaint.get('complainant_placeholder', '')}")
    doc.add_paragraph(f"Respondent: {complaint.get('respondent_placeholder', '')}")
    doc.add_paragraph("")

    doc.add_heading("Subject", level=2)
    doc.add_paragraph(complaint.get("issue_summary", ""))

    doc.add_heading("Description", level=2)
    doc.add_paragraph(complaint.get("description", ""))

    doc.add_heading("Relief Requested", level=2)
    doc.add_paragraph(complaint.get("relief_requested", ""))

    attachments = complaint.get("attachments", [])
    if attachments:
        doc.add_heading("Attachments", level=2)
        for item in attachments:
            doc.add_paragraph(str(item), style="List Bullet")

    doc.add_paragraph("")
    doc.add_paragraph(complaint.get("signature_placeholder", "[Signature]\n[Date]"))
    doc.add_paragraph("")
    doc.add_paragraph(
        "Generated by LexAI — general educational assistance, not a substitute "
        "for a lawyer. Review before submitting."
    ).italic = True

    doc.save(output_path)
    return output_path
